import type {
  FullSlug,
  QuartzComponent,
  QuartzComponentConstructor,
  QuartzComponentProps,
} from "@quartz-community/types";
import type { VNode } from "preact";
import { knownConflict, renderConflict } from "../conflict";
import { knownCountry, renderCountry } from "../country";
import { knownElection, renderElection } from "../election";
import { knownPerson, renderPerson } from "../person";
import { type Fields, type RenderCtx, hasValue, normalizeKeys } from "../render";
// @ts-expect-error - inline script import handled by the bundler
import script from "./scripts/infobox.inline.ts";

export interface InfoboxOptions {
  /** Frontmatter key that names the infobox type. Defaults to "infobox". */
  typeKey?: string;
}

type Renderer = (fields: Fields, ctx: RenderCtx, fallbackTitle: string) => VNode | null;
type InfoboxType = { render: Renderer; known: RegExp };

const country: InfoboxType = { render: renderCountry, known: knownCountry };
const person: InfoboxType = { render: renderPerson, known: knownPerson };
const conflict: InfoboxType = { render: renderConflict, known: knownConflict };
const election: InfoboxType = { render: renderElection, known: knownElection };

/**
 * Keys that belong to Quartz, Obsidian or the old Chronicler rather than the infobox.
 * They are never shown as extra rows.
 */
const META =
  /^(?:infobox|title|tags|aliases|layout|draft|publish|permalink|description|date|created|modified|lastmod|updated|published|cssclass|cssclasses|enabletoc|comments|lang|socialimage|socialdescription|password|unlisted)$/;

/** Infobox types, keyed by the value of `infobox:` in a page's frontmatter. */
const renderers: Record<string, InfoboxType> = {
  country,
  nation: country,
  former_country: country,
  person,
  officeholder: person,
  politician: person,
  royalty: person,
  monarch: person,
  military_person: person,
  biography: person,
  conflict,
  war: conflict,
  battle: conflict,
  military_conflict: conflict,
  election,
  conclave: election,
};

export default ((opts?: InfoboxOptions) => {
  const typeKey = (opts?.typeKey ?? "infobox").toLowerCase();

  const Infobox: QuartzComponent = ({ fileData, allFiles }: QuartzComponentProps) => {
    const fields = normalizeKeys(fileData.frontmatter as Record<string, unknown> | undefined);
    const type = fields[typeKey];
    if (typeof type !== "string") return null;
    const infoboxType = renderers[type.trim().toLowerCase().replace(/[\s-]+/g, "_")];
    if (!infoboxType) return null;

    // Original spelling of each key, so extra rows keep your labels ("Historical era").
    const original = new Map<string, string>();
    for (const key of Object.keys((fileData.frontmatter as Record<string, unknown> | undefined) ?? {})) {
      original.set(key.trim().toLowerCase().replace(/[\s-]+/g, "_"), key.trim());
    }
    const extras = Object.entries(fields)
      .filter(([key, value]) => !META.test(key) && !infoboxType.known.test(key) && hasValue(value))
      .map(([key, value]) => ({ label: original.get(key) ?? key, value }));

    const ctx: RenderCtx = {
      src: fileData.slug as FullSlug,
      // Tag pages (tags/moremia) are generated by Quartz, not written by you, so they
      // must not make [[Moremia]] look like an existing page.
      extras,
      allSlugs: allFiles
        .map((f) => f.slug as string | undefined)
        .filter((slug): slug is string => typeof slug === "string" && !slug.startsWith("tags/")) as FullSlug[],
    };
    const fallbackTitle = typeof fields.title === "string" ? fields.title : "";
    const box = infoboxType.render(fields, ctx, fallbackTitle);
    if (!box) return null;
    // Styles come from the plugin's transformer (see transformer.ts), not Component.css.
    return box;
  };

  Infobox.afterDOMLoaded = script;
  return Infobox;
}) satisfies QuartzComponentConstructor<InfoboxOptions>;
